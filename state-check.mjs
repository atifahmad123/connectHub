import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundled = await build({ entryPoints: ['src/state.ts'], bundle: true, platform: 'node', format: 'esm', write: false });
const { initialState, prototypeReducer } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
let state = initialState(), sequence = 0;
const send = action => { state = prototypeReducer(state, { ...action, meta: { id: `test-${++sequence}`, now: new Date().toISOString() } }); };
const air = () => state.instances.airUniversity;
const cv = () => state.instances.crescentValley;
const originalCv = structuredClone(cv());
assert.equal(air().alumni.filter(p => p.status === 'approved').length, 24);
assert.equal(cv().alumni.filter(p => p.status === 'approved').length, 14);
assert.ok(!JSON.stringify(state.instances).includes('universityId'));
for (const data of Object.values(state.instances)) {
  const ids = new Set(data.alumni.map(p => p.id));
  for (const c of data.connections) assert.ok(ids.has(c.senderId) && ids.has(c.recipientId));
  for (const r of data.sessions) assert.ok(ids.has(r.mentorAlumniId) && ids.has(r.requesterAlumniId));
  for (const o of data.opportunities) assert.ok(ids.has(o.postedByAlumniId));
}
send({ type: 'SEND_CONNECTION', recipientId: 'cv-1' });
assert.equal(air().connections.length, 5, 'No cross-instance recipients');
send({ type: 'SEND_CONNECTION', recipientId: 'air-2' });
const c = air().connections[0];
assert.equal(c.status, 'pending');
send({ type: 'SEND_CONNECTION', recipientId: 'air-2' });
assert.equal(air().connections.length, 6, 'Duplicate requests prevented');
send({ type: 'RESPOND_CONNECTION', id: c.id, status: 'accepted' });
assert.equal(air().connections[0].status, 'pending', 'Sender cannot accept');
send({ type: 'SELECT_ALUMNI', id: 'air-2' });
send({ type: 'RESPOND_CONNECTION', id: c.id, status: 'accepted' });
assert.equal(air().connections[0].status, 'accepted');
assert.ok(air().notifications.some(n => n.userId === 'air-1' && n.title === 'Connection accepted'));
const applicant = air().pendingRegistrations.find(p => p.status === 'pending');
send({ type: 'REVIEW_REGISTRATION', id: applicant.id, approve: true });
assert.ok(air().pendingRegistrations.some(p => p.id === applicant.id), 'Alumni cannot approve');
send({ type: 'SWITCH_ROLE', role: 'admin' });
send({ type: 'REVIEW_REGISTRATION', id: applicant.id, approve: false });
assert.equal(air().pendingRegistrations.find(p => p.id === applicant.id).status, 'pending', 'Reason required');
send({ type: 'REVIEW_REGISTRATION', id: applicant.id, approve: true });
assert.ok(air().alumni.some(p => p.id === applicant.id && p.status === 'approved'));
assert.equal(air().auditLogs[0].action, 'ALUMNI_APPROVED');
assert.ok(air().notifications.some(n => n.userId === applicant.id));
const rejected = air().pendingRegistrations.find(p => p.status === 'pending');
send({ type: 'REVIEW_REGISTRATION', id: rejected.id, approve: false, reason: 'Incomplete evidence' });
send({ type: 'SWITCH_ROLE', role: 'alumni' });
send({ type: 'SELECT_ALUMNI', id: rejected.id });
send({ type: 'SUBMIT_REGISTRATION', profile: { ...rejected, evidenceName: 'replacement.pdf' } });
assert.equal(air().pendingRegistrations.find(p => p.id === rejected.id).status, 'pending');
assert.equal(air().pendingRegistrations.filter(p => p.id === rejected.id).length, 1);
send({ type: 'SELECT_ALUMNI', id: 'air-1' });
const r = { id: 'test-session', requesterAlumniId: 'air-1', mentorAlumniId: 'air-2', topic: 'Architecture', message: 'Career advice', preferredAt: '2027-01-01T15:00', requestedAt: '2026-09-27', status: 'pending' };
send({ type: 'REQUEST_SESSION', session: r });
send({ type: 'RESPOND_SESSION', id: r.id, status: 'completed' });
assert.equal(air().sessions[0].status, 'pending', 'Cannot skip the lifecycle');
send({ type: 'SELECT_ALUMNI', id: 'air-2' });
send({ type: 'RESPOND_SESSION', id: r.id, status: 'accepted' });
send({ type: 'RESPOND_SESSION', id: r.id, status: 'scheduled', scheduledAt: '2027-01-01T15:00', meetingLink: 'javascript:alert(1)' });
assert.equal(air().sessions[0].status, 'accepted', 'Meeting links require HTTP(S)');
send({ type: 'RESPOND_SESSION', id: r.id, status: 'scheduled', scheduledAt: '2027-01-01T15:00', meetingLink: 'https://example.com/meeting' });
send({ type: 'RESPOND_SESSION', id: r.id, status: 'completed' });
send({ type: 'SESSION_FEEDBACK', id: r.id, rating: 5, comment: 'Helpful conversation' });
assert.equal(air().sessions[0].feedback['air-2'].rating, 5);
const job = { ...air().opportunities[0], id: 'test-job', postedByAlumniId: 'air-2' };
send({ type: 'SUBMIT_OPPORTUNITY', opportunity: job });
assert.equal(air().opportunities[0].status, 'pending_review');
send({ type: 'SWITCH_ROLE', role: 'admin' });
send({ type: 'MODERATE_OPPORTUNITY', id: job.id, approve: true });
assert.equal(air().opportunities[0].status, 'published');
const announcement = { ...air().announcements[0], id: 'targeted', department: air().alumni[0].department, publishedAt: new Date().toISOString().slice(0, 10), expiresAt: undefined };
send({ type: 'CREATE_ANNOUNCEMENT', announcement });
const recipients = air().notifications.filter(n => n.body === announcement.title && n.id.startsWith(`test-${sequence}-`));
assert.equal(recipients.length, air().alumni.filter(p => p.status === 'approved' && p.department === announcement.department).length);
send({ type: 'UPDATE_SAFE_SETTINGS', settings: { ...air().config, primary: '#24665A', featureFlags: { messaging: true } } });
assert.equal(air().config.featureFlags.messaging, false, 'Safe settings cannot grant features');
assert.deepEqual(cv(), originalCv, 'Every mutation leaves the other dataset untouched');
send({ type: 'SWITCH_INSTANCE', id: 'crescentValley' });
send({ type: 'SWITCH_ROLE', role: 'alumni' });
const frozenCv = structuredClone(cv());
send({ type: 'REQUEST_SESSION', session: { ...r, requesterAlumniId: 'cv-1', mentorAlumniId: 'cv-2' } });
send({ type: 'SUBMIT_OPPORTUNITY', opportunity: { ...job, postedByAlumniId: 'cv-1' } });
assert.deepEqual(cv(), frozenCv, 'Disabled feature actions are rejected');
send({ type: 'SELECT_ALUMNI', id: 'air-2' });
assert.equal(state.selectedAlumni.crescentValley, 'cv-1');
send({ type: 'RESET_DEMO' });
assert.deepEqual(state.instances, initialState().instances);
console.log('PASS: domain transitions, role checks, notification recipients, lifecycle constraints, entitlement allowlist, dataset isolation, and reset.');
